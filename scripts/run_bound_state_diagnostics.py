"""Reproduce impurity-bound-state spectral diagnostics for capacity revivals.

This is *not* a real-space bound-state removal experiment: we replace
out-of-band eigenenergies with their nearest band edge while leaving
eigenvectors and all band energies unchanged. The resulting counterfactual
evolution is unitary but is generated by a generally nonlocal Hamiltonian.

Outputs:
  results/bound_state_spectral_summary.csv
  results/bound_state_trajectories.csv
  figures/bound_state_phase_ablation.png
"""
from pathlib import Path
import csv
import sys

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"src"))
from scattering_phase import initial_modes
from bound_state_diagnostics import defective_hamiltonian,capacity_spectral_diagnostics
from revival_benchmark import first_broad_capacity_peak

LENGTHS=(48,64)
ONSITE=((1.2,.35),(.35,1.2),(.7,1.4),(1.4,.7),(.5,.2),(.2,.5))
STEP=.2
M=2.5


def main():
    (ROOT/"results").mkdir(exist_ok=True)
    (ROOT/"figures").mkdir(exist_ok=True)
    summaries=[]
    timeseries=[]
    fig,axs=plt.subplots(2,1,figsize=(8.1,7.5))
    for length in LENGTHS:
        times=np.arange(0,1.8*length+STEP*.1,STEP)
        occupied=initial_modes(length,"staggered",stagger=M)
        # Weak hopping with NO on-site potentials: a physical bound-free
        # control, not a perfect transmission-matched comparison.
        cases=[(f"onsite:{u:g},{v:g}",(u,v),1.) for u,v in ONSITE]
        cases.append(("weak_bond:0.5",(0.,0.),.5))
        for label,pair,hop in cases:
            data=capacity_spectral_diagnostics(
                defective_hamiltonian(length,pair,central_hopping=hop),
                occupied,times)
            arr=data["values"]
            first_ref=first_broad_capacity_peak(times,arr[:,1],length)
            first_counter=first_broad_capacity_peak(times,arr[:,3],length)
            mask=(times>=.4*length)&(times<=1.65*length)
            summary=dict(
                label=label,
                L=length,
                num_bound=data["num_bound"],
                bound_energies=";".join(f"{x:.9f}" for x in data["bound_energies"]),
                central_8_site_weight=";".join(f"{x:.7f}" for x in data["central_weights"]),
                peak_full_time=first_ref[0],
                peak_counterfactual_time=first_counter[0],
                peak_full_capacity=first_ref[1],
                peak_counterfactual_capacity=first_counter[1],
                peak_time_difference=first_ref[0]-first_counter[0],
                peak_capacity_difference=first_ref[1]-first_counter[1],
                window_mae_capacity=float(np.mean(np.abs(arr[mask,1]-arr[mask,3]))),
                window_max_abs_capacity_difference=float(
                    np.max(np.abs(arr[mask,1]-arr[mask,3]))),
                mean_band_bound_cross_fro=float(np.mean(arr[mask,5])),
            )
            summaries.append(summary)
            for t,values in zip(times,arr):
                timeseries.append(dict(
                    label=label,L=length,time=float(t),
                    entropy_full=values[0],capacity_full=values[1],
                    entropy_phase_ablation=values[2],capacity_phase_ablation=values[3],
                    fro_bound_bound=values[4],
                    fro_band_bound_cross=values[5],
                    fro_band_band=values[6],
                ))
            print(label,"L",length,"num_bound",summary["num_bound"],
                  "peak shift",round(summary["peak_time_difference"],3),
                  "MAE",round(summary["window_mae_capacity"],3))
            if label=="onsite:1.2,0.35":
                ax=axs[0 if length==48 else 1]
                ax.plot(times,arr[:,1],label="Exact physical evolution")
                ax.plot(times,arr[:,3],ls="--",label="Unitary bound-energy counterfactual")
                ax.set_ylabel("Modular capacity [nats²]")
                ax.set_title(f"L={length}; bound-state energy sensitivity")
                ax.legend(fontsize=8)
    for ax in axs:ax.set_xlabel("Evolution time [hbar/hopping]")
    fig.suptitle("Diagnostic phase ablation: not a physical bound-free defect")
    fig.tight_layout()
    fig.savefig(ROOT/"figures"/"bound_state_phase_ablation.png",dpi=180)
    plt.close(fig)
    for name,rows in (("bound_state_spectral_summary.csv",summaries),
                      ("bound_state_trajectories.csv",timeseries)):
        with (ROOT/"results"/name).open("w",newline="") as out:
            w=csv.DictWriter(out,fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)


if __name__=="__main__":
    main()
